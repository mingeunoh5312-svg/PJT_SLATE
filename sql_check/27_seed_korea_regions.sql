INSERT INTO region (region_code, sido_name, sigungu_name, dong_name, center_lat, center_lng, public_display_name, active_yn)
SELECT s.region_code, s.sido_name, s.sigungu_name, s.dong_name, s.center_lat, s.center_lng, s.public_display_name, 'Y'
FROM tmp_korea_region_seed s
ON DUPLICATE KEY UPDATE
  sido_name = VALUES(sido_name),
  sigungu_name = VALUES(sigungu_name),
  dong_name = VALUES(dong_name),
  center_lat = VALUES(center_lat),
  center_lng = VALUES(center_lng),
  public_display_name = VALUES(public_display_name),
  active_yn = 'Y';

UPDATE member_profile mp
JOIN region old_region ON old_region.region_id = mp.region_id
JOIN tmp_korea_region_seed s ON s.public_display_name = old_region.public_display_name
JOIN region new_region ON new_region.region_code = s.region_code
SET mp.region_id = new_region.region_id
WHERE old_region.region_code <> s.region_code;

UPDATE team t
JOIN region old_region ON old_region.region_id = t.region_id
JOIN tmp_korea_region_seed s ON s.public_display_name = old_region.public_display_name
JOIN region new_region ON new_region.region_code = s.region_code
SET t.region_id = new_region.region_id
WHERE old_region.region_code <> s.region_code;

DELETE old_region
FROM region old_region
JOIN tmp_korea_region_seed s ON s.public_display_name = old_region.public_display_name
JOIN region new_region ON new_region.region_code = s.region_code
WHERE old_region.region_id <> new_region.region_id
  AND old_region.region_code <> s.region_code;

SELECT COUNT(*) AS active_region_count
FROM region
WHERE active_yn = 'Y';
